/**
 * Unsubscribe routes — RFC 8058 compliant one-click unsubscribe.
 *
 * GET  /api/unsubscribe?email=…&tok=…
 *   → Validates the HMAC token, then renders a confirmation page with a
 *     <form method="POST"> button. Does NOT mutate the DB on GET — protects
 *     against corporate/Outlook/security link-prefetchers that follow every
 *     link in an email before the user sees it (silent opt-out risk).
 *
 * POST /api/unsubscribe?email=…&tok=…
 *   → Validates token, sets opted_out_at on members + registrations, returns
 *     success page. Handles both:
 *       a) Manual form submissions (from the GET confirmation page).
 *       b) RFC 8058 machine one-click posts from email clients (body =
 *          "List-Unsubscribe=One-Click", application/x-www-form-urlencoded).
 *
 * Token: HMAC-SHA256(SESSION_SECRET, "unsub:" + email.toLowerCase())
 * Generated by email.ts at send time; embedded in the List-Unsubscribe header
 * (for RFC 8058 clients) and the visible footer link (for manual clicks).
 */
import { Router, type IRouter } from "express";
import { createHmac, timingSafeEqual } from "crypto";
import { eq } from "drizzle-orm";
import { db, membersTable, registrationsTable } from "@workspace/db";

const router: IRouter = Router();

/**
 * Compute the HMAC-SHA256 unsubscribe token for a given email address.
 * Exported so tests can generate valid tokens without going through the API.
 */
export function makeUnsubToken(email: string): string {
  return createHmac("sha256", process.env.SESSION_SECRET ?? "")
    .update(`unsub:${email.toLowerCase()}`)
    .digest("hex");
}

