// ── Token validation helper ───────────────────────────────────────────────────

function validateToken(email: unknown, tok: unknown): boolean {
  if (!email || !tok || typeof email !== "string" || typeof tok !== "string") return false;
  const expected = makeUnsubToken(email);
  try {
    const expBuf = Buffer.from(expected, "hex");
    const tokBuf = Buffer.from(tok, "hex");
    return expBuf.length === tokBuf.length && timingSafeEqual(expBuf, tokBuf);
  } catch { return false; }
}

// ── GET — confirmation page (NO DB mutation) ──────────────────────────────────

router.get("/unsubscribe", (req, res): void => {
  const { email, tok } = req.query as { email?: string; tok?: string };

  if (!email || !tok || typeof email !== "string" || typeof tok !== "string") {
    res.status(400).send(page(
      "Invalid link",
      "<p>This unsubscribe link is missing required parameters. Please use the link from your email.</p>",
    ));
    return;
  }

  if (!validateToken(email, tok)) {
    res.status(400).send(page(
      "Invalid link",
      "<p>This unsubscribe link isn&#39;t valid. It may have been modified. Please use the original link from your email.</p>",
    ));
    return;
  }

  // Token valid — show the confirmation page. No DB mutation on GET.
  const action = `/api/unsubscribe?email=${encodeURIComponent(email)}&tok=${encodeURIComponent(tok)}`;

  res.status(200).send(page(
    "Confirm unsubscribe",
    `<p>Are you sure you want to stop receiving emails from P3 at <strong>${email}</strong>?</p>
     <form method="POST" action="${action}">
       <button type="submit" class="btn">Yes, unsubscribe me</button>
     </form>
     <p><a href="https://www.padelcubed.co.uk" class="btn btn-ghost">No, keep me on the list</a></p>`,
  ));
});

// ── POST — actual opt-out (RFC 8058 one-click + manual form) ─────────────────
//
// Accepts both:
//   a) application/x-www-form-urlencoded  { "List-Unsubscribe": "One-Click" }
//      — sent by RFC 8058-compliant email clients (Gmail, Apple Mail, …)
//   b) An empty POST body from the confirmation form above
//
// In both cases the email + tok come from the URL query string.

router.post("/unsubscribe", async (req, res): Promise<void> => {
  const { email, tok } = req.query as { email?: string; tok?: string };

  if (!email || !tok || typeof email !== "string" || typeof tok !== "string") {
    res.status(400).send(page(
      "Invalid link",
      "<p>This unsubscribe link is missing required parameters.</p>",
    ));
    return;
  }

  if (!validateToken(email, tok)) {
    res.status(400).send(page(
      "Invalid link",
      "<p>This unsubscribe link isn&#39;t valid. Please use the original link from your email.</p>",
    ));
    return;
  }

  const now = new Date();
  const lowerEmail = email.toLowerCase();

  try {
    // Set opted_out_at on member account if one exists
    await db
      .update(membersTable)
      .set({ optedOutAt: now })
      .where(eq(membersTable.email, lowerEmail));

    // Set opted_out_at on registration record if one exists
    await db
      .update(registrationsTable)
      .set({ optedOutAt: now })
      .where(eq(registrationsTable.email, lowerEmail));

    res.status(200).send(page(
      "You&#39;ve been unsubscribed",
      `<p>We&#39;ve removed <strong>${email}</strong> from our mailing list. You won&#39;t receive any further emails from P3.</p>
       <p>Changed your mind? <a href="https://www.padelcubed.co.uk">Re-register at padelcubed.co.uk</a>.</p>`,
    ));
  } catch (err) {
    console.error("[unsubscribe]", err);
    res.status(500).send(page(
      "Something went wrong",
      "<p>We couldn&#39;t process your request right now. Please reply to the email you received and we&#39;ll sort it manually.</p>",
    ));
  }
});

export default router;
